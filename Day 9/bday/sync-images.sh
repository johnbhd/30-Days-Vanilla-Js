#!/usr/bin/env bash
# Scans current directory (bday/) and optional img/ subfolder for image files
# and writes images-manifest.js for instant loading in index.html.

set -e
cd "$(dirname "$0")"

OUT="images-manifest.js"

echo "// Auto-generated by sync-images.sh — lists all friendship & birthday photos in the folder" > "$OUT"
echo "window.FOLDER_IMAGES = [" >> "$OUT"

shopt -s nullglob nocaseglob
count=0
for f in *.jpg *.jpeg *.png *.webp *.gif img/*.jpg img/*.jpeg img/*.png img/*.webp img/*.gif; do
  if [ -f "$f" ]; then
    echo "  \"$f\"," >> "$OUT"
    count=$((count + 1))
  fi
done

echo "];" >> "$OUT"
echo "Synced $count images into $OUT"
